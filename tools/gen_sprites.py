def head(name):
    k = {".": T, "o": DARK, "c": COL, "l": LIGHT, "w": WHITE, "k": BLACK}
    rows = HEADS[name]
    assert len(rows) == HH and all(len(r) == HW for r in rows), name
    return [[k[ch] for ch in r] for r in rows]


def main():
    L = ["/* generated by tools/gen_sprites.py: the four tracks' heads, 4 bits a pixel (op_pal in ui_op.c: 1 dark, 2 the",
         " * track's colour, 3 light, 4 white, 5 black), the first pixel of a byte in its low half. OP_SPR_HM[track]. */",
         "#pragma once", f"#define OP_HM_W {HW}", f"#define OP_HM_H {HH}"]
    total = 0
    for name in NAMES:
        px = [v for row in head(name) for v in row]
        by = [px[i] | (px[i + 1] << 4) for i in range(0, len(px), 2)]
        total += len(by)
        L.append(f"static const uint8_t OP_SPR_{name}_HM[{len(by)}] = {{")
        for i in range(0, len(by), 28):
            L.append("    " + ",".join(str(b) for b in by[i:i + 28]) + ",")
        L.append("};")
    L.append("static const uint8_t *const OP_SPR_HM[4] = {%s};" % ", ".join("OP_SPR_%s_HM" % n for n in NAMES))
    OUT.write_text("\n".join(L) + "\n")
    print(OUT, total, "B")
    if len(sys.argv) > 1:
        from PIL import Image
        s = 8
        sheet = Image.new("RGB", (4 * (HW * s + 16) + 16, HH * s + 32), (30, 30, 34))
        for r, name in enumerate(NAMES):
            pal = shades(TRACK_RGB[r])
            rgb = Image.new("RGB", (HW, HH))
            rgb.putdata([pal[v] for row in head(name) for v in row])
            sheet.paste(rgb.resize((HW * s, HH * s), Image.NEAREST), (16 + r * (HW * s + 16), 16))
        sheet.save(sys.argv[1])


if __name__ == "__main__":
    main()
